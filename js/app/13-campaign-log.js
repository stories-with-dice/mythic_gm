// Copy and Download export the log oldest first (the order of `campaign().log`);
// the on-screen view (renderLogHtml()) passes newestFirst = true.
function buildLogMarkdown(newestFirst){
  const camp = campaign();
  const name = STORE.current;
  let md = `# Campaign Log — ${name}\n\n_Generated by Mythic Toolkit — ${timestamp()}_\n\n`;
  if(!camp.log.length){
    md += "_No results logged yet. Roll something on any tab and it will appear here._\n";
    return md;
  }
  (newestFirst ? camp.log.slice().reverse() : camp.log).forEach(entry=>{
    md += `### ${entry.ts} — ${entry.section}\n${entry.md}\n\n`;
  });
  return md;
}
// The on-screen view, newest first. Each entry is a row: a time column
// (HH:MM, the full timestamp and section in its title) and the entry's own
// Markdown. A date row starts each new day. The section name shows only when
// the entry's Markdown does not start with a bold label (a Quick Note).
// Copy / Download keep the full Markdown with the "### ts — section" headings.
function renderLogHtml(){
  const log = campaign().log;
  if(!log.length) return `<p class="log-empty">No results logged yet. Roll something on any tab and it will appear here.</p>`;
  let day = null, html = '';
  log.slice().reverse().forEach(e => {
    const ts = String(e.ts || '');
    const d = ts.slice(0, 10), time = ts.slice(11, 16) || ts;
    if(d !== day){ day = d; html += `<div class="log-day">${escapeAttr(d)}</div>`; }
    const md = String(e.md || '');
    const tag = /^\s*\*\*/.test(md) ? '' : `<span class="log-tag">${escapeAttr(e.section)}</span>`;
    html += `<div class="log-entry"><time title="${escapeAttr(ts + ' — ' + e.section)}">${escapeAttr(time)}</time><div class="log-md">${tag}${marked.parse(md)}</div></div>`;
  });
  return DOMPurify.sanitize(html);
}
function renderLogSection(){
  const host = document.getElementById('logSection');
  const scrollEl = document.getElementById('logRender');
  // Newest entry is at the top: stay at the top, or keep the entries you
  // scrolled to in place (same distance from the bottom) when one is added.
  const fromBottom = scrollEl && scrollEl.scrollTop > 4 ? scrollEl.scrollHeight - scrollEl.scrollTop : null;
  host.innerHTML = `
  <h2 class="tool-title">Campaign Log</h2>
  <p class="tool-desc">Every roll from every tab in this campaign, newest first. Copy or download it as Markdown.</p>
  <div class="log-toolbar">
    <div class="small-note">${campaign().log.length} entries — campaign "${STORE.current}"</div>
    <div class="right">
      <button class="btn small" id="btnCopyLog">Copy Markdown</button>
      <button class="btn small" id="btnDownloadLog">Download .md</button>
      <button class="btn small danger" id="btnClearLog">Clear log</button>
    </div>
  </div>
  <div class="log-render" id="logRender">${renderLogHtml()}</div>
  `;
  wireLogSection();
  const newScrollEl = document.getElementById('logRender');
  if(newScrollEl) newScrollEl.scrollTop = fromBottom === null ? 0 : Math.max(0, newScrollEl.scrollHeight - fromBottom);
}
function wireLogSection(){
  document.getElementById('btnCopyLog').addEventListener('click', ()=>{
    const md = buildLogMarkdown();
    navigator.clipboard.writeText(md).then(()=>{
      const btn = document.getElementById('btnCopyLog');
      const original = btn.textContent;
      btn.textContent = "Copied!";
      setTimeout(()=>{ btn.textContent = original; }, 1400);
    }).catch(()=>{
      alert("Could not copy automatically — select the text below and copy manually.");
    });
  });
  document.getElementById('btnDownloadLog').addEventListener('click', ()=>{
    const md = buildLogMarkdown();
    const blob = new Blob([md], {type:'text/markdown'});
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${STORE.current.replace(/[^a-z0-9\-_]+/gi,'_')}_log.md`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  });
  // Clear runs at once; the toast offers Undo for UNDO_MS (04).
  document.getElementById('btnClearLog').addEventListener('click', ()=>{
    const c = campaign(), name = STORE.current, before = c.log;
    if(!before.length) return;
    c.log = [];
    persist();
    renderLogSection();
    showUndoToast(`Cleared the log of "${name}".`, ()=>{
      const back = STORE.campaigns[name];
      if(!back) return;
      back.log = before.concat(back.log);   // keep anything logged since the clear
      persist();
      renderLogSection();
    });
  });
}
