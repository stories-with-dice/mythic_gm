/* =========================================================================
   CAMPAIGN LOG
   ========================================================================= */
function buildLogMarkdown(){
  const camp = campaign();
  const name = STORE.current;
  let md = `# Campaign Log — ${name}\n\n_Generated by Mythic Toolkit — ${timestamp()}_\n\n`;
  if(!camp.log.length){
    md += "_No results logged yet. Roll something on any tab and it will appear here._\n";
    return md;
  }
  camp.log.forEach(entry=>{
    md += `### ${entry.ts} — ${entry.section}\n${entry.md}\n\n`;
  });
  return md;
}
function renderLogHtml(){
  const rawHtml = marked.parse(buildLogMarkdown());
  return DOMPurify.sanitize(rawHtml);
}
function renderLogSection(){
  const host = document.getElementById('logSection');
  const scrollEl = document.getElementById('logRender');
  const wasScrolledToBottom = scrollEl ? (scrollEl.scrollTop + scrollEl.clientHeight >= scrollEl.scrollHeight - 4) : true;
  host.innerHTML = `
  <h2 class="tool-title">Campaign Log</h2>
  <p class="tool-desc">Every roll from every tab, rendered from Markdown for this campaign. Copy or download it as Markdown to keep alongside your session notes.</p>
  <div class="log-toolbar">
    <div class="small-note">${campaign().log.length} entries — campaign "${STORE.current}"</div>
    <div class="right">
      <button class="btn small" id="btnCopyLog">Copy Markdown</button>
      <button class="btn small" id="btnDownloadLog">Download .md</button>
      <button class="btn small danger" id="btnClearLog">Clear log</button>
    </div>
  </div>
  <div class="log-render" id="logRender">${renderLogHtml()}</div>
  `;
  wireLogSection();
  const newScrollEl = document.getElementById('logRender');
  if(newScrollEl && wasScrolledToBottom) newScrollEl.scrollTop = newScrollEl.scrollHeight;
}
function wireLogSection(){
  document.getElementById('btnCopyLog').addEventListener('click', ()=>{
    const md = buildLogMarkdown();
    navigator.clipboard.writeText(md).then(()=>{
      const btn = document.getElementById('btnCopyLog');
      const original = btn.textContent;
      btn.textContent = "Copied!";
      setTimeout(()=>{ btn.textContent = original; }, 1400);
    }).catch(()=>{
      alert("Could not copy automatically — select the text below and copy manually.");
    });
  });
  document.getElementById('btnDownloadLog').addEventListener('click', ()=>{
    const md = buildLogMarkdown();
    const blob = new Blob([md], {type:'text/markdown'});
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${STORE.current.replace(/[^a-z0-9\-_]+/gi,'_')}_log.md`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  });
  document.getElementById('btnClearLog').addEventListener('click', ()=>{
    if(!confirm("Clear the entire log for this campaign? This cannot be undone.")) return;
    campaign().log = [];
    persist();
    renderLogSection();
  });
}
